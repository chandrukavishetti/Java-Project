package com.chandru.reduce_else;

public class Switch_case {
	public static void main(String[] args) {
		String day = "monday";
		switch (day) {
		case "monday":
			System.out.println("moday");
			break;
		case "tuesday":
			System.out.println("tuesday");
			break;
		default:
			System.out.println("invalid");
		}
	}

}
